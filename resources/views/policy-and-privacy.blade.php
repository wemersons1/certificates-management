        <h2 class="section-title">Política de Privacidade da Flash Certificados</h2>
        <p class="section-desc">Entenda como seus dados e os dados de seus alunos são coletados, usados e protegidos em nossa plataforma.</p>

        <p>Esta Política de Privacidade descreve como a Flash Certificados ("nós", "nosso" ou "a Empresa") coleta, usa e protege as informações pessoais que você fornece ao utilizar a plataforma Flash Certificados ("Serviço").</p>
        <p>Ao utilizar o Serviço, você concorda com a coleta e uso de suas informações conforme descrito nesta política.</p>

        <h4>1. Informações que Coletamos</h4>
        <p>Coletamos diferentes tipos de informações para fornecer e melhorar nosso Serviço a você, com foco especial na automação de certificados e documentos:</p>
        <ul>
            <li><strong>Informações de Cadastro:</strong> Nome completo, endereço de e-mail e senha ao criar uma conta. Essas informações são essenciais para gerenciar seu acesso à plataforma.</li>
            <li><strong>Informações de Pagamento:</strong> Quando você contrata um plano pago, coletamos informações de transação (mas não os dados completos do seu cartão de crédito, que são processados por gateways de pagamento seguros de terceiros).</li>
            <li><strong>Dados de Utilização:</strong> Informações sobre como o Serviço é acessado e utilizado, como páginas visitadas, tempo gasto, recursos utilizados (ex: número de certificados gerados), endereço IP, tipo de navegador, etc. Isso nos ajuda a otimizar a experiência do usuário.</li>
            <li><strong>Conteúdo do Usuário (Dados para Certificados):</strong> Dados que você carrega na plataforma para a emissão de certificados e documentos, como nomes e CPFs de alunos, informações de cursos, datas, cargas horárias, modelos de templates, logotipos e assinaturas. Esses dados são processados estritamente para a finalidade de geração dos seus documentos.</li>
            <li><strong>Informações de Contato:</strong> Dados fornecidos ao entrar em contato conosco para suporte ou outras consultas, garantindo que possamos atendê-lo de forma eficiente.</li>
        </ul>

        <h4>2. Como Usamos Suas Informações</h4>
        <p>Utilizamos as informações coletadas para diversas finalidades, sempre visando aprimorar a emissão de certificados e a sua experiência:</p>
        <ul>
            <li>Para fornecer, manter e aprimorar o Serviço de geração e emissão de certificados.</li>
            <li>Para gerenciar sua conta e processar suas transações de planos e certificados.</li>
            <li>Para personalizar e melhorar sua experiência na plataforma, oferecendo funcionalidades e sugestões relevantes.</li>
            <li>Para enviar notificações importantes relacionadas ao Serviço, como alertas de vencimento de certificados ou atualizações da plataforma.</li>
            <li>Para fornecer suporte ao cliente de forma eficaz, ajudando-o com qualquer dúvida ou problema.</li>
            <li>Para monitorar o uso do Serviço e detectar, prevenir e resolver problemas técnicos, garantindo a estabilidade da plataforma.</li>
            <li>Para fins de análise e pesquisa, a fim de entender o comportamento do usuário, otimizar nossos algoritmos de geração de certificados e desenvolver novas funcionalidades.</li>
            <li>Para cumprir obrigações legais e regulatórias.</li>
        </ul>

        <h4>3. Compartilhamento de Suas Informações</h4>
        <p>Não vendemos, trocamos ou alugamos suas informações pessoais ou os dados de seus alunos a terceiros. Podemos compartilhar suas informações nas seguintes situações, sempre com o máximo de segurança:</p>
        <ul>
            <li><strong>Com Prestadores de Serviços:</strong> Podemos empregar empresas e indivíduos terceirizados para facilitar nosso Serviço (ex: hospedagem de servidores, análise de dados, processamento de pagamentos, serviços de e-mail), que terão acesso às suas informações apenas para executar essas tarefas em nosso nome e são obrigados contratualmente a não divulgá-las ou usá-las para qualquer outra finalidade.</li>
            <li><strong>Para Cumprimento da Lei:</strong> Podemos divulgar suas informações se exigido por lei ou em resposta a solicitações válidas de autoridades públicas (ex: uma ordem judicial ou solicitação governamental), sempre em conformidade com a legislação aplicável.</li>
            <li><strong>Com o Seu Consentimento:</strong> Podemos compartilhar suas informações com terceiros para qualquer outro propósito com o seu consentimento expresso.</li>
        </ul>

        <h4>4. Segurança dos Dados</h4>
        <p>A segurança dos seus dados e dos certificados gerados é de suma importância para nós. Implementamos medidas de segurança técnicas e organizacionais rigorosas para proteger suas informações pessoais contra acesso não autorizado, alteração, divulgação ou destruição, incluindo criptografia e controles de acesso. Seus certificados são armazenados de forma segura com validação por código único.</p>
        <p>No entanto, lembre-se que nenhum método de transmissão pela Internet ou método de armazenamento eletrônico é 100% seguro. Embora nos esforcemos para usar meios comercialmente aceitáveis para proteger suas informações, não podemos garantir sua segurança absoluta.</p>

        <h4>5. Seus Direitos (LGPD)</h4>
        <p>Em conformidade com a Lei Geral de Proteção de Dados (LGPD - Lei nº 13.709/2018) e outras leis aplicáveis, você, como titular dos dados, pode ter os seguintes direitos em relação às suas informações pessoais:</p>
        <ul>
            <li>Acessar e obter uma cópia dos seus dados pessoais que mantemos.</li>
            <li>Solicitar a correção de dados incompletos, inexatos ou desatualizados.</li>
            <li>Solicitar a exclusão de dados pessoais (sujeito a certas exceções legais, como a necessidade de manter registros para cumprimento de obrigações legais).</li>
            <li>Opor-se ao processamento dos seus dados em determinadas circunstâncias.</li>
            <li>Solicitar a portabilidade dos seus dados para outro serviço ou fornecedor, mediante requisição expressa e observados os segredos comercial e industrial.</li>
            <li>Retirar seu consentimento a qualquer momento (quando o processamento for baseado no consentimento).</li>
            <li>Informar-se sobre as entidades públicas e privadas com as quais a Flash Certificados realizou uso compartilhado de dados.</li>
        </ul>
        <p>Para exercer qualquer um desses direitos, entre em contato conosco através do e-mail [E-mail de Contato]. Faremos o possível para responder à sua solicitação dentro de um prazo razoável.</p>

        <h4>6. Cookies</h4>
        <p>Este site utiliza "cookies" para melhorar a sua experiência de navegação e para coletar informações sobre como você interage com o nosso Serviço. Cookies são pequenos arquivos de texto armazenados no seu dispositivo.</p>
        <p>Usamos cookies para:</p>
        <ul>
            <li>Lembrar suas preferências e configurações de idioma ou funcionalidades.</li>
            <li>Autenticar sua sessão, mantendo você logado na plataforma de forma segura.</li>
            <li>Analisar o tráfego do site e entender o comportamento do usuário, o que nos ajuda a aprimorar a plataforma e suas funcionalidades.</li>
            <li>Personalizar conteúdo e anúncios relevantes para você.</li>
        </ul>
        <p>Você pode configurar seu navegador para recusar todos os cookies ou para indicar quando um cookie está sendo enviado. No entanto, se você não aceitar cookies, talvez não consiga usar algumas partes do nosso Serviço ou ter uma experiência completa.</p>

        <h4>7. Links para Outros Sites</h4>
        <p>Nosso Serviço pode conter links para outros sites que não são operados por nós. Se você clicar em um link de terceiros, será direcionado ao site desse terceiro. Aconselhamos vivamente que você revise a Política de Privacidade de cada site que visitar, pois não temos controle sobre eles.</p>
        <p>Não temos controle e não assumimos responsabilidade pelo conteúdo, políticas de privacidade ou práticas de quaisquer sites ou serviços de terceiros.</p>

        <h4>8. Privacidade de Crianças e Adolescentes</h4>
        <p>Nosso Serviço não se destina a menores de 18 anos. Não coletamos intencionalmente informações de identificação pessoal de crianças ou adolescentes. Se você é pai/mãe ou responsável e percebe que seu filho nos forneceu informações pessoais, entre em contato conosco para que possamos tomar as medidas necessárias para remover esses dados de nossos sistemas.</p>

        <h4>9. Alterações nesta Política de Privacidade</h4>
        <p>Podemos atualizar nossa Política de Privacidade periodicamente para refletir mudanças em nossas práticas ou na legislação. Notificaremos você sobre quaisquer alterações significativas publicando a nova Política de Privacidade nesta página e atualizando a "Data da última atualização" no final desta política. Recomendamos que você revise esta Política periodicamente para se manter informado.</p>

